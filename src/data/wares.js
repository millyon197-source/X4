export function getWareWorkforceMultiplier(wareOrId, workforceBonus = 0) {
  const ware = typeof wareOrId === 'string' ? WARES_DB[wareOrId] : wareOrId;
  if (!ware) return 1;
  const maxWf = typeof ware.maxWorkforce === 'number' ? ware.maxWorkforce : 0;
  if (maxWf === 0) return 1;
  return 1 + (maxWf * (workforceBonus / 100));
}

